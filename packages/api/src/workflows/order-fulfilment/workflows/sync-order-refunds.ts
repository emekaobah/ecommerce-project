import type { IOrderModuleService, IPaymentModuleService } from "@medusajs/framework/types"
import { ContainerRegistrationKeys, Modules } from "@medusajs/framework/utils"
import { emitEventStep } from "@medusajs/medusa/core-flows"
import { StepResponse, WorkflowResponse, createStep, createWorkflow, transform } from "@medusajs/framework/workflows-sdk"
import { fulfilmentService, ORDER_REFUND_NEEDS_ATTENTION, ORDER_REFUND_PROCESSED, type OrderRefundRecord } from "../../../lib/order-fulfilment"
import { syncOrderPhases } from "../../../lib/order-phase"
import { paystackClient } from "../../../modules/paystack"
import { UNSETTLED_REFUND_STATUSES, type PaystackRefundStatus } from "../../../modules/paystack/client"

type CreditLines = {
  listOrderCreditLines(filters: { reference: string; reference_id: string[] }): Promise<{ id: string }[]>
  deleteOrderCreditLines(ids: string[]): Promise<void>
}

type Change = { id: string; from: PaystackRefundStatus; to: PaystackRefundStatus; row: OrderRefundRecord }

/** Paystack's word on each unsettled order refund of the transaction, where it has moved on. */
const fetchRefundChangesStep = createStep("fetch-order-refund-changes", async ({ transaction_reference: reference }: { transaction_reference: string }, { container }) => {
  const paystack = paystackClient()
  if (!paystack) return new StepResponse([] as Change[])
  const rows = (await fulfilmentService(container).listOrderRefunds({
    transaction_reference: reference,
    status: UNSETTLED_REFUND_STATUSES,
  })) as OrderRefundRecord[]
  const logger = container.resolve(ContainerRegistrationKeys.LOGGER)
  for (const row of rows.filter((r) => !r.paystack_refund_id)) {
    logger.warn(`Order refund ${row.id} has no Paystack refund id to check`)
  }
  // Each refund is fetched on its own, so they are asked about at once.
  const fetched = await Promise.all(
    rows
      .filter((row) => row.paystack_refund_id)
      .map(async (row) => ({ row, status: (await paystack.fetchRefund(row.paystack_refund_id!)).status }))
  )
  const changes: Change[] = fetched
    .filter(({ row, status }) => status !== row.status)
    .map(({ row, status }) => ({ id: row.id, from: row.status, to: status, row }))
  return new StepResponse(changes)
})

/**
 * A refund that now needs attention records when (#13): the buyer's reminders count from then.
 * Each order's phase is rewritten by its refunds' new statuses (#59): one waiting on the buyer's
 * bank account holds it in progress.
 */
const updateRefundStatusesStep = createStep(
  "update-order-refund-statuses",
  async (changes: Change[], { container }) => {
    const now = new Date()
    if (changes.length) {
      await fulfilmentService(container).updateOrderRefunds(
        changes.map((c) => ({ id: c.id, status: c.to, ...(c.to === "needs-attention" && { needs_attention_at: now }) }))
      )
      await syncOrderPhases(container, changes.map((c) => c.row.order_id))
    }
    return new StepResponse(undefined, changes)
  },
  async (changes: Change[] | undefined, { container }) => {
    if (changes?.length) {
      await fulfilmentService(container).updateOrderRefunds(
        changes.map((c) => ({ id: c.id, status: c.from, needs_attention_at: c.row.needs_attention_at }))
      )
      await syncOrderPhases(container, changes.map((c) => c.row.order_id))
    }
  }
)

/**
 * A failed refund (Paystack credited the money back) no longer counts as refunded: its order
 * transaction and Medusa refund are removed, so the order may be refunded again.
 */
const unrecordFailedRefundsStep = createStep("unrecord-failed-order-refunds", async (changes: Change[], { container }) => {
  // A refund made on Paystack directly, of a transaction no order claims, has no Medusa refund.
  const failed = changes
    .filter((c) => c.to === "failed")
    .map((c) => c.row.refund_id)
    .filter((id): id is string => !!id)
  if (!failed.length) return new StepResponse(undefined)
  const orderModule = container.resolve<IOrderModuleService>(Modules.ORDER)
  const transactions = await orderModule.listOrderTransactions({
    reference: "refund",
    reference_id: failed,
  })
  if (transactions.length) await orderModule.deleteOrderTransactions(transactions.map((t) => t.id))
  // Generated by the order module from its OrderCreditLine model, but missing from its types.
  const creditLines = orderModule as unknown as CreditLines
  const credits = await creditLines.listOrderCreditLines({ reference: "refund", reference_id: failed })
  if (credits.length) await creditLines.deleteOrderCreditLines(credits.map((c) => c.id))
  await container.resolve<IPaymentModuleService>(Modules.PAYMENT).deleteRefunds(failed)
  return new StepResponse(undefined)
})

/**
 * Brings the order refunds of a Paystack transaction up to date. Paystack's `refund.*`
 * webhooks name the transaction but not the refund, so each unsettled refund is fetched by
 * its id. An order's refund that reaches processed emits `order_refund.processed`, once: a
 * settled refund isn't fetched again, however often Paystack repeats the webhook. A refund
 * that moves to needs-attention emits `order_refund.needs_attention`, each time it does (#13).
 */
export const syncOrderRefundsWorkflow = createWorkflow("sync-order-refunds", (input: { transaction_reference: string }) => {
  const changes = fetchRefundChangesStep(input)
  updateRefundStatusesStep(changes)
  unrecordFailedRefundsStep(changes)
  const processed = transform({ changes }, ({ changes }) =>
    changes.filter((c) => c.to === "processed" && c.row.order_id).map((c) => ({ id: c.id }))
  )
  emitEventStep({ eventName: ORDER_REFUND_PROCESSED, data: processed })
  const needsAttention = transform({ changes }, ({ changes }) =>
    changes.filter((c) => c.to === "needs-attention").map((c) => ({ id: c.id }))
  )
  emitEventStep({ eventName: ORDER_REFUND_NEEDS_ATTENTION, data: needsAttention }).config({ name: "emit-order-refund-needs-attention" })
  return new WorkflowResponse(changes)
})
